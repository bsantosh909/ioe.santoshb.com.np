/**
 * Regenerates `src/data/courses.generated.ts` from the MDX frontmatter in
 * `src/content/courses` and `src/content/notes`. Run after adding or
 * editing content files:
 *
 *   node scripts/sync-course-index.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { basename, join } from 'node:path'
import matter from 'gray-matter'

const ROOT = new URL('..', import.meta.url).pathname
const COURSES = join(ROOT, 'src/content/courses')
const NOTES = join(ROOT, 'src/content/notes')
const OUT = join(ROOT, 'src/data/courses.generated.ts')

// Optional per-tab SEO override fields carried through from frontmatter.
const SEO_FIELDS = [
  'seoTitle',
  'seoDescription',
  'seoSyllabusTitle',
  'seoSyllabusDescription',
  'seoOldqTitle',
  'seoOldqDescription',
]

/**
 * Top-level unit headings from the `## Syllabus` section — the bold text of
 * each unindented numbered item (`1. **Introduction** (3 hours)`).
 */
function syllabusUnits(body) {
  const section = body.match(/^## Syllabus\s*$([\s\S]*?)(?=^## |(?![\s\S]))/m)
  if (!section) return []
  return [...section[1].matchAll(/^\d+\.\s+\*\*(.+?)\*\*/gm)].map((match) =>
    match[1].trim(),
  )
}

const courses = []
for (const file of readdirSync(COURSES).sort()) {
  if (!file.endsWith('.mdx')) continue
  const { data, content } = matter(readFileSync(join(COURSES, file), 'utf8'))
  const course = {
    slug: data.slug ?? basename(file, '.mdx'),
    code: data.code ?? null,
    title: data.title,
    objective: data.objective ?? '',
    units: syllabusUnits(content),
  }
  for (const field of SEO_FIELDS) {
    if (data[field] != null) course[field] = String(data[field])
  }
  courses.push(course)
}

const notes = []
for (const file of readdirSync(NOTES).sort()) {
  if (!file.endsWith('.mdx')) continue
  const { data } = matter(readFileSync(join(NOTES, file), 'utf8'))
  notes.push({ slug: data.slug, course: data.course, title: data.title })
}

const banner =
  '// Generated by scripts/sync-course-index.mjs — do not edit by hand.\n' +
  "import type { CourseMeta } from '#/features/courses/types'\n" +
  "import type { NoteMeta } from '#/features/notes/types'\n\n"
writeFileSync(
  OUT,
  banner +
    `export const COURSE_INDEX: Array<CourseMeta> = ${JSON.stringify(courses, null, 2)}\n` +
    `\nexport const NOTE_INDEX: Array<NoteMeta> = ${JSON.stringify(notes, null, 2)}\n`,
)
console.log(`Indexed ${courses.length} courses and ${notes.length} notes.`)
