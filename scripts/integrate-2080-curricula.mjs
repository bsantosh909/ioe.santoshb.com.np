/**
 * One-time integration of the extracted 2080 curriculum JSON into
 * `src/features/programs/data/curricula-2080.generated.ts`, and of the
 * course-code mapping into the course MDX frontmatter.
 *
 * Inputs (produced by the extraction agent):
 *   $SCRATCH/ioe-2080-curricula.json
 *   $SCRATCH/course-code-mapping.json
 *
 * Usage: node scripts/integrate-2080-curricula.mjs <scratch-dir>
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import matter from 'gray-matter'

const ROOT = new URL('..', import.meta.url).pathname
const SCRATCH = process.argv[2]
if (!SCRATCH)
  throw new Error('pass the scratch dir containing the extraction JSON files')

const curricula = JSON.parse(
  readFileSync(join(SCRATCH, 'ioe-2080-curricula.json'), 'utf8'),
)
const mapping = JSON.parse(
  readFileSync(join(SCRATCH, 'course-code-mapping.json'), 'utf8'),
)

// Wire curriculum subjects to course pages. Primary key is the course code;
// a normalized-title fallback catches subjects that share one page across
// programs under different codes (e.g. Computer Organization & Architecture
// is ENCT303 in BCT but ENEX253 in BEX — one page, two curriculum codes).
const { readdirSync } = await import('node:fs')
const slugByCode = new Map()
const slugByTitle = new Map()

const normalizeTitle = (title) =>
  String(title)
    .toLowerCase()
    .replace(
      /\b(i{1,3}|iv)\b/g,
      (n) => ({ i: '1', ii: '2', iii: '3', iv: '4' })[n],
    ) // roman → arabic
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()

for (const entry of mapping.mappings) {
  if (entry.confidence === 'high' && entry.newCode) {
    slugByCode.set(entry.newCode.replace(/\s+/g, ''), entry.slug)
  }
}
const coursesDir = join(ROOT, 'src/content/courses')
for (const file of readdirSync(coursesDir)) {
  if (!file.endsWith('.mdx')) continue
  const { data } = matter(readFileSync(join(coursesDir, file), 'utf8'))
  const slug = data.slug ?? file.replace(/\.mdx$/, '')
  if (data.code) slugByCode.set(String(data.code).replace(/\s+/g, ''), slug)
  if (data.title) slugByTitle.set(normalizeTitle(data.title), slug)
}

function subjectLiteral(subject) {
  const code = subject.code ? subject.code.replace(/\s+/g, '') : null
  const slug =
    (code ? slugByCode.get(code) : undefined) ??
    slugByTitle.get(normalizeTitle(subject.title))
  const parts = [`title: ${JSON.stringify(subject.title)}`]
  if (code) parts.push(`code: '${code}'`)
  if (slug) parts.push(`slug: '${slug}'`)
  if (subject.credits != null) parts.push(`credits: ${subject.credits}`)
  if (subject.marks != null) parts.push(`marks: ${subject.marks}`)
  return `{ ${parts.join(', ')} }`
}

const blocks = curricula.programs.map((program) => {
  const years = program.years
    .map((year) => {
      const parts = year.parts
        .map((part) => {
          const subjects = part.subjects
            .map((s) => `          ${subjectLiteral(s)},`)
            .join('\n')
          return `        {\n          part: ${part.part},\n          subjects: [\n${subjects}\n          ],\n        },`
        })
        .join('\n')
      return `      {\n        year: ${year.year},\n        parts: [\n${parts}\n        ],\n      },`
    })
    .join('\n')

  const electives = (program.electiveGroups ?? [])
    .map((group, index) => {
      const choices = group.choices
        .map((c) => `          ${subjectLiteral(c)},`)
        .join('\n')
      const id = `${program.abbr.toLowerCase()}-2080-elective-${index + 1}`
      const codeRange = group.codeRange
        ? `\n        codeRange: '${group.codeRange}',`
        : ''
      return `      {\n        id: '${id}',\n        title: ${JSON.stringify(group.name)},${codeRange}\n        choices: [\n${choices}\n        ],\n      },`
    })
    .join('\n')

  const electiveBlock = electives
    ? `\n    electiveGroups: [\n${electives}\n    ],`
    : ''
  return `  ${program.abbr}: {\n    years: [\n${years}\n    ],${electiveBlock}\n  },`
})

const output =
  `// Generated by scripts/integrate-2080-curricula.mjs from official IOE\n` +
  `// curriculum pages (fetched ${curricula.fetchedAt}) — do not edit by hand.\n` +
  `import type { Curriculum } from '#/features/programs/types'\n\n` +
  `export const CURRICULA_2080: Record<string, Curriculum> = {\n${blocks.join('\n')}\n}\n`

writeFileSync(
  join(ROOT, 'src/features/programs/data/curricula-2080.generated.ts'),
  output,
)
console.log(
  `Wrote curricula for: ${curricula.programs.map((p) => p.abbr).join(', ')}`,
)

// Apply high-confidence new codes to course MDX frontmatter.
let updated = 0
for (const entry of mapping.mappings) {
  if (entry.confidence !== 'high' || !entry.newCode) continue
  const path = join(ROOT, `src/content/courses/${entry.slug}.mdx`)
  const raw = readFileSync(path, 'utf8')
  const { data } = matter(raw)
  if (data.code) continue
  const code = entry.newCode.replace(/\s+/g, '')
  writeFileSync(path, raw.replace(/^slug: (.+)$/m, `slug: $1\ncode: ${code}`))
  updated += 1
}
console.log(`Applied new codes to ${updated} course MDX files.`)
